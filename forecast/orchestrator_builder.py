"""
forecast/orchestrator_builder.py: Scorecard entry synthesis and simulation response packaging
for multi-scenario forecast orchestration.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional


def build_scenario_scorecard_entry(
    scen: Dict[str, Any],
    scen_events: List[Dict[str, Any]],
    scen_primary_ret: int,
    scen_spouse_ret: int,
    primary_birth_year: int,
    spouse_birth_year: int,
    scen_spending: float,
    scen_savings: float,
    scen_inflation: float,
    scen_primary_ss_claim: int,
    scen_spouse_ss_claim: int,
    growth_us: float,
    growth_intl: float,
    growth_bonds_rate: float,
    growth_cash_rate: float,
    growth_private: float,
    growth_re: float,
    scen_blended_liquid: float,
    scen_blended_retire: float,
    ret_readiness: Dict[str, Any],
    bal_65: float,
    bal_85: float,
    bal_95: float,
    scen_growth_preset: str,
    scen_holding_presets: Dict[str, str],
    scen_equity_annual_growth: float,
    preset_info: Dict[str, Any],
    sim_out: Dict[str, Any],
    active_scen_id: str,
) -> Dict[str, Any]:
    """Constructs a comprehensive comparison scorecard row for a scenario."""
    scen_id = scen["id"]
    return {
        "id": scen_id,
        "name": scen["name"],
        "description": scen.get("description", ""),
        "color": scen.get("color", "#1D4ED8"),
        "event_count": len(scen_events),
        "events_included": [e["name"] for e in scen_events],
        "events_details": [
            {
                "id": e.get("id"),
                "name": e.get("name"),
                "icon": e.get("icon") or "",
                "category": e.get("category"),
                "year": e.get("year"),
                "end_year": e.get("end_year"),
                "amount": e.get("annual_amount") or e.get("amount") or 0.0,
                "is_inherited": e.get("id") in scen.get("inherited_event_ids", []),
                "is_added": e.get("id") in scen.get("added_event_ids", []),
                "sync_with_ledger": bool(e.get("sync_with_ledger", e.get("id", "").startswith("evt_k12_"))),
                "child_user_id": e.get("child_user_id"),
                "child_name": e.get("child_name"),
                "benchmark_tier": e.get("benchmark_tier"),
            }
            for e in scen_events
        ],
        "primary_retirement_age": scen_primary_ret,
        "primary_retirement_year": primary_birth_year + scen_primary_ret,
        "spouse_retirement_age": scen_spouse_ret,
        "spouse_retirement_year": spouse_birth_year + scen_spouse_ret,
        "annual_living_spend": scen_spending,
        "annual_savings": scen_savings,
        "inflation_rate": scen_inflation,
        "ss_claim_age": scen_primary_ss_claim,
        "primary_ss_claim_age": scen_primary_ss_claim,
        "spouse_ss_claim_age": scen_spouse_ss_claim,
        "growth_us_equity": growth_us,
        "growth_intl_equity": growth_intl,
        "growth_bonds": growth_bonds_rate,
        "growth_cash": growth_cash_rate,
        "growth_private_investments": growth_private,
        "growth_real_estate": growth_re,
        "blended_liquid_growth": round(scen_blended_liquid, 4),
        "blended_retire_growth": round(scen_blended_retire, 4),
        "retirement_readiness": ret_readiness,
        "net_worth_65": round(bal_65, 2),
        "net_worth_85": round(bal_85, 2),
        "net_worth_95": round(bal_95, 2),
        "equity_growth_preset": scen_growth_preset,
        "spending_guardrail_mode": scen.get("spending_guardrail_mode") or "off",
        "equity_growth_presets": scen_holding_presets,
        "equity_growth_rate": scen_equity_annual_growth,
        "equity_growth_label": preset_info.get("short_name", f"{scen_growth_preset.title()} (+{scen_equity_annual_growth*100:.1f}%/yr)"),
        "equity_growth_full_name": preset_info.get("name", ""),
        "is_depleted": sim_out["depleted"],
        "is_active": (scen_id == active_scen_id),
        "is_baseline": scen.get("is_baseline", False),
        "parent_id": scen.get("parent_id"),
        "parent_name": scen.get("parent_name"),
        "ancestor_ids": scen.get("ancestor_ids", []),
        "depth": scen.get("depth", 0),
        "overrides": scen.get("overrides", {}),
        "event_ids": scen.get("event_ids", []),
        "inherited_event_ids": scen.get("inherited_event_ids", []),
        "added_event_ids": scen.get("added_event_ids", []),
        "excluded_event_ids": scen.get("excluded_event_ids", []),
    }


def package_simulation_response(
    view_mode: str,
    equity_growth_preset: str,
    equity_annual_growth: float,
    primary_retirement_age: int,
    spouse_retirement_age: int,
    primary_name: str,
    spouse_name: str,
    current_primary_age: int,
    current_spouse_age: int,
    annual_living_spend: float,
    annual_savings: float,
    inflation_rate: float,
    primary_ss_claim_age: int,
    spouse_ss_claim_age: int,
    active_scen_id: str,
    active_readiness: Any,
    scorecard: List[Dict[str, Any]],
    comparison_curves: List[Dict[str, Any]],
    milestones: List[Dict[str, Any]],
    events_catalog: Dict[str, Any],
    scenarios_list: List[Dict[str, Any]],
    children_edu: List[Dict[str, Any]],
    active_result: Dict[str, Any],
    scenarios_results: Dict[str, Any],
    historical_ribbon: Any,
    historical_cash_flow_series: Any,
    equity_companies_list: List[Dict[str, Any]],
    w_us: float,
    w_intl: float,
    w_bonds: float,
    w_cash: float,
    mortgage_start: float,
    real_estate_start: float,
    family_id: int,
    prof_spending: float,
) -> Dict[str, Any]:
    """Packages all simulation outputs, spending benchmarks, and metadata into the final response dict."""
    import monarch_service
    from forecast.catalog import REINVESTMENT_PRESETS, EQUITY_GROWTH_PRESETS
    from forecast.presets import build_living_budget_presets, build_annual_savings_presets, get_scenario_templates

    spending_meta = monarch_service.get_monarch_spending_history(family_id=family_id)
    spending_benchmarks = spending_meta.get("benchmarks", {})
    spending_history = spending_meta.get("spending_history", {})
    spending_presets = build_living_budget_presets(
        spending_benchmarks,
        baseline_spend=float(spending_benchmarks.get("baseline") or 0.0),
        target_spend=float(annual_living_spend or prof_spending or 0.0),
    )
    savings_presets = build_annual_savings_presets(
        baseline_savings=float(annual_savings or 0.0),
        annual_compensation=0.0,
    )

    return {
        "success": True,
        "view_mode": view_mode,
        "equity_growth_preset": equity_growth_preset,
        "equity_growth_rate": equity_annual_growth,
        "primary_retirement_age": primary_retirement_age,
        "spouse_retirement_age": spouse_retirement_age,
        "primary_name": primary_name,
        "spouse_name": spouse_name,
        "primary_current_age": current_primary_age,
        "spouse_current_age": current_spouse_age,
        "annual_living_spend": annual_living_spend,
        "annual_savings": annual_savings,
        "inflation_rate": inflation_rate,
        "primary_ss_claim_age": primary_ss_claim_age,
        "spouse_ss_claim_age": spouse_ss_claim_age,
        "ss_claim_age": primary_ss_claim_age,
        "active_scenario_id": active_scen_id,
        "active_retirement_readiness": active_readiness,
        "scorecard": scorecard,
        "comparison_curves": comparison_curves,
        "milestones": milestones,
        "events_catalog": list(events_catalog.values()),
        "scenarios": scenarios_list,
        "scenario_templates": get_scenario_templates(family_id=family_id, children_edu=children_edu),
        "active_schedule": active_result["schedule"],
        "active_cash_flow_series": active_result["cash_flow_series"],
        "active_longevity_breakdown": active_result["longevity_breakdown"],
        "scenario_schedules": {scen_id: s["schedule"] for scen_id, s in scenarios_results.items()},
        "scenario_cash_flows": {scen_id: s["cash_flow_series"] for scen_id, s in scenarios_results.items()},
        "scenario_longevity_breakdowns": {scen_id: s["longevity_breakdown"] for scen_id, s in scenarios_results.items()},
        "historical_ribbon": historical_ribbon,
        "historical_cash_flow_series": historical_cash_flow_series,
        "reinvestment_presets": list(REINVESTMENT_PRESETS.values()),
        "equity_growth_presets": list(EQUITY_GROWTH_PRESETS.values()),
        "equity_companies": equity_companies_list,
        "asset_weights": {
            "us_equity": round(w_us * 100, 1),
            "intl_equity": round(w_intl * 100, 1),
            "bonds": round(w_bonds * 100, 1),
            "cash": round(w_cash * 100, 1),
            "us": round(w_us * 100, 1),
            "intl": round(w_intl * 100, 1),
        },
        "spending_benchmarks": spending_benchmarks,
        "spending_history": spending_history,
        "spending_presets": spending_presets,
        "savings_presets": savings_presets,
        "current_mortgage_balance": round(mortgage_start, 2),
        "current_real_estate_value": round(real_estate_start, 2),
    }
